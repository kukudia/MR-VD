using System;
using System.IO;
using System.Text;

/// <summary>
/// Standalone deterministic PCM fixture authoring; invoked by Generate-ReferenceAudio.ps1.
/// Produces no playback, capture or external media. All signals are authored from equations.
/// </summary>
public static class ReferenceAudioGenerator
{
    private const int SampleRate = 48000;
    private const int Seconds = 6;

    public static void Generate(string directory)
    {
        Directory.CreateDirectory(directory);
        string[] names = { "low-tone", "high-tone", "harmonic-bed", "broadband-bursts", "mixed-bed-bursts", "silence" };
        for (int kind = 0; kind < names.Length; kind++)
        {
            uint random = 8457;
            string path = Path.Combine(directory, names[kind] + ".wav");
            using (BinaryWriter writer = new BinaryWriter(File.Create(path)))
            {
                int bytes = SampleRate * Seconds * 2;
                writer.Write(Encoding.ASCII.GetBytes("RIFF"));
                writer.Write(36 + bytes);
                writer.Write(Encoding.ASCII.GetBytes("WAVEfmt "));
                writer.Write(16);
                writer.Write((short)1);
                writer.Write((short)1);
                writer.Write(SampleRate);
                writer.Write(SampleRate * 2);
                writer.Write((short)2);
                writer.Write((short)16);
                writer.Write(Encoding.ASCII.GetBytes("data"));
                writer.Write(bytes);
                for (int sample = 0; sample < SampleRate * Seconds; sample++)
                {
                    double t = sample / (double)SampleRate;
                    random ^= random << 13;
                    random ^= random >> 17;
                    random ^= random << 5;
                    double noise = random / (double)uint.MaxValue * 2.0 - 1.0;
                    double beatAge = t % 0.5;
                    // Bursts start after one second to supply a genuine silent/persistent baseline.
                    double burst = t >= 1.0 && beatAge < 0.06
                        ? noise * Math.Sin(Math.PI * beatAge / 0.06) * Math.Exp(-beatAge * 35.0) * 0.65 : 0.0;
                    double bed = (Math.Sin(2.0 * Math.PI * 110.0 * t)
                        + Math.Sin(2.0 * Math.PI * 220.0 * t) * 0.5
                        + Math.Sin(2.0 * Math.PI * 440.0 * t) * 0.25) * 0.23;
                    double signal = kind == 0 ? Math.Sin(2.0 * Math.PI * 110.0 * t) * 0.35
                        : kind == 1 ? Math.Sin(2.0 * Math.PI * 3520.0 * t) * 0.35
                        : kind == 2 ? bed : kind == 3 ? burst : kind == 4 ? bed * 0.65 + burst : 0.0;
                    double fade = Math.Min(1.0, Math.Min(t / 0.02, (Seconds - t) / 0.02));
                    writer.Write((short)Math.Round(Math.Max(-1.0, Math.Min(1.0, signal * fade)) * 32767.0));
                }
            }
        }
        File.WriteAllText(Path.Combine(directory, "sources.txt"),
            "Original procedural PCM fixtures. 48000 Hz mono signed 16-bit, 6 seconds. Seed 8457.\n"
            + "Low 110Hz; high 3520Hz; bed 110/220/440Hz; bursts seeded broadband every 0.5sec after 1sec.\n"
            + "Generated by Tools/AudioVisualResearch/ReferenceAudioGenerator.cs. No external media.\n"
            + "Controlled signal checks only, not representative musical listening validation.\n");
    }
}
